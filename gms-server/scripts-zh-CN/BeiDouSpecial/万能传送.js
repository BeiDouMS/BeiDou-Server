function levelDangerTaxi(selection) {
	let dest = dangertaximaps[selection];
	let mapId = dest[0];
	let cost = dest[1];
	let portal = dest[3];
	// 星级出租车：新手职业 90% 折扣（对齐 1002004 / 1032005）
	if (mapId === 105070001 && cm.getJobId() === 0) {
		cost = 1000;
	}
	// 海豚出租车海底叉路：随机靠近通天塔入口的门户（对齐 2060009）
	if (portal === -1) {
		let nearOrbis = [13, 18];
		portal = nearOrbis[Math.floor(Math.random() * nearOrbis.length)];
	}
	cm.gainMeso(-cost);
	cm.getPlayer().saveLocationOnWarp();
	cm.warp(mapId, portal);
	cm.dispose();
}

